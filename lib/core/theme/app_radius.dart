/// Shared corner radii used across the design system.
abstract final class AppRadius {
  /// Checkbox/small control radius.
  static const double checkbox = 6;

  /// Text field radius.
  static const double input = 24;

  /// Card radius.
  static const double card = 36;

  /// Large decorative panel radius (onboarding illustrations).
  static const double panel = 44;

  /// Pill buttons and badges use a fully rounded (stadium) corner.
  static const double pill = 999;
}
